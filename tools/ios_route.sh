#!/usr/bin/env bash
# Машина едет по Ашхабаду: от дома в Парахате до садика «Bagtyýar».
#
# Симулятор не умеет ездить сам, а без движения не проверить ни карту у
# родителя, ни трекинг у водителя. Точки идут с запада на восток по
# Магтымгулы — симулятор тянет прямую между соседними точками, поэтому
# их несколько: одна прямая через весь город на карте выглядела бы
# неправдой.
#
# Скорость по умолчанию 8 м/с (~29 км/ч) — городская с остановками.
# Весь путь около 5 км, то есть примерно 10 минут: достаточно, чтобы
# успеть посмотреть на оба экрана.
#
#   ./tools/ios_route.sh                      # на устройство водителя
#   ./tools/ios_route.sh "QA-ProMax"          # на конкретный симулятор
#   SPEED=20 ./tools/ios_route.sh             # быстрее, если некогда ждать
#
# Сбросить точку — ./tools/ios_route.sh clear
set -euo pipefail

DEVICE=${1:-booted}
SPEED=${SPEED:-8}

# Парахат 7 → садик «Bagtyýar». Координаты настоящие: Ашхабад,
# восточные микрорайоны к центру.
WAYPOINTS=(
  37.9192,58.4204  # Парахат 7, дом 12 — откуда забирают
  37.9231,58.4102
  37.9288,58.3971
  37.9339,58.3842
  37.9372,58.3719
  37.9401,58.3608  # садик «Bagtyýar»
)

if [ "$DEVICE" = "clear" ]; then
  xcrun simctl location booted clear
  echo "Местоположение сброшено."
  exit 0
fi

echo "Маршрут: Парахат 7 → садик «Bagtyýar», ${SPEED} м/с"
echo "Устройство: $DEVICE"
echo
echo "Чтобы родитель увидел движение, у водителя должна быть начата"
echo "поездка: трекинг включается с её началом, а не с запуском приложения."
echo
echo "Прервать — Ctrl+C. Сбросить точку — ./tools/ios_route.sh clear"
echo

# --interval=2: обновление раз в две секунды. Чаще нет смысла, реже —
# машина на карте начинает прыгать.
exec xcrun simctl location "$DEVICE" start \
  --speed="$SPEED" --interval=2 "${WAYPOINTS[@]}"
