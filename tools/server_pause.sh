#!/usr/bin/env bash
# Проверка поведения без связи: авиарежима в симуляторе нет.
#
# Замораживает процесс сервера (SIGSTOP) и размораживает (SIGCONT).
# Перезапуска нет: сессии, открытые WebSocket'ы и лог остаются на месте,
# а приложение видит ровно то, что видит в метро — запросы уходят и не
# возвращаются.
#
# Это «сервер не отвечает», а не «нет сети»: сокет остаётся открытым,
# поэтому приложение упирается в таймаут, а не получает отказ сразу.
# Для проверки офлайн-очереди водителя это и нужно — именно так выглядит
# пропавшая связь в дороге, а мгновенный отказ выглядит иначе.
#
#   ./tools/server_pause.sh pause     # сервер замолчал
#   ./tools/server_pause.sh resume    # сервер отвечает снова
#   ./tools/server_pause.sh status
set -euo pipefail
cd "$(dirname "$0")/.."

find_pid() {
  pgrep -f "bin/main.dart" | head -1
}

PID=$(find_pid || true)

if [ -z "$PID" ]; then
  echo "Сервер не запущен. Запустите ./tools/dev_up.sh" >&2
  exit 1
fi

# T — остановлен, S/R — работает.
state() { ps -o stat= -p "$1" | tr -d ' ' | cut -c1; }

case "${1:-status}" in
  pause)
    if [ "$(state "$PID")" = "T" ]; then
      echo "Сервер уже на паузе (PID $PID)."
      exit 0
    fi
    kill -STOP "$PID"
    echo "Пауза: сервер не отвечает (PID $PID)."
    echo
    echo "Что должно произойти в приложениях:"
    echo "  • родитель — «нет связи с сервером», карта с последним известным местом;"
    echo "  • водитель — этапы поездки нажимаются и копятся в очереди на телефоне;"
    echo "  • после «resume» очередь уходит сама, терять ничего не должно."
    ;;
  resume)
    if [ "$(state "$PID")" != "T" ]; then
      echo "Сервер и так работает (PID $PID)."
      exit 0
    fi
    kill -CONT "$PID"
    echo "Сервер отвечает снова (PID $PID)."
    echo "Очередь водителя должна уйти в течение нескольких секунд."
    ;;
  status)
    if [ "$(state "$PID")" = "T" ]; then
      echo "На паузе (PID $PID)."
    else
      echo "Работает (PID $PID)."
    fi
    ;;
  *)
    echo "использование: $0 pause|resume|status" >&2
    exit 1
    ;;
esac
