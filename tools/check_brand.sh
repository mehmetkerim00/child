#!/usr/bin/env bash
# Проверка написания домена перед сборкой.
#
# Бренд пишется Sag-Aman, через дефис. Домен — sagaman.tm, слитно.
# Разница в один символ, но это два разных доменных имени: приложение,
# собранное на api.sag-aman.tm, просто не найдёт сервер — и узнаем мы об
# этом от семей, у которых APK уже стоит.
#
# Адрес зашит в APK. Поймать опечатку здесь стоит секунду, поймать её
# после раздачи — новую версию у каждой семьи.
#
# Запускается в CI и первым шагом приёмки: tools/check_brand.sh
set -uo pipefail
cd "$(dirname "$0")/.."

# Сам этот файл написание домена обсуждает, поэтому из поиска исключён.
hits=$(git grep -n -- 'sag-aman' -- . ':(exclude)tools/check_brand.sh' 2>/dev/null || true)

if [ -n "$hits" ]; then
  echo "НАЙДЕН домен с дефисом — должно быть sagaman.tm:" >&2
  echo "$hits" | sed 's/^/    /' >&2
  echo >&2
  echo "Собирать APK с таким адресом нельзя: приложение не найдёт сервер." >&2
  exit 1
fi

echo "Домен написан верно: sagaman.tm"
