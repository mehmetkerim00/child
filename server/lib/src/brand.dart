/// Имя сервиса в текстах, которые видит человек.
///
/// Вынесено в одно место не ради красоты: бренд появляется в SMS, в push,
/// на странице учреждения и в тревогах владельцу. Когда он менялся в
/// прошлый раз, в коде нашлось девять мест — и это были только те,
/// которые нашёл поиск.
///
/// В applicationId и доменах бренд не отсюда: их менять после публикации
/// нельзя, поэтому они прописаны явно в сборке и конфигах.
abstract final class Brand {
  /// Как сервис подписывается в SMS и push: «Sag-Aman: Мерет передан».
  static const name = 'Sag-Aman';

  /// Подпись в подвале страницы учреждения — по языку читателя.
  static String tagline(String locale) => switch (locale) {
    'tk' => '$name — çagalary howpsuz gatnatmak',
    'en' => '$name — safe rides for children',
    _ => '$name — безопасные детские перевозки',
  };
}
